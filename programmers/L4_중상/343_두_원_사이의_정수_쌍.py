"""
[구하고자 하는 것]
1. 반지름이 각각 r1, r2인 원이 차지하는 영역 중, 겹치지지 않는 영역에 존재하는 x,y가 모두 정수인 점의 개수
    - 단, 원 위에 있는 점도 포함하여 측정
    
[계산해야 하는 것]
1. 두 원의 원주 위에 존재하는 점의 y 좌표
    - 중심이 (0,0)이고 반지름이 r인 원 위의 점은 x^2 + y^2 = r^2을 만족하므로 y의 최댓값은 (r^2 - x^2)^(1/2)
    
2. 지정된 영역에서 x=n일 때, 양수인 y의 개수는 y.max - y.min + 1

3. 원점을 기준으로 대칭이므로, 1사분면에서 점 개수를 구하고 *4를 하면 구하고자 하는 값이 나올 것

4. y값을 계산할때, x는 1부터 세야 함 -> x=1임에도 불구하고 좌표롤 찍어보니 count해야 하는 경우도 있기 때문에
    - 단, y값을 계싼하는 과정에서 r1 < x가 커지면 '(r^2 - x^2)^(1/2)'가 실수가 될 수 없으므로 0으로 처리
"""
import math

def solution(r1, r2):
    # 1-1. 제 1사분면에서 나올 수 있는 점의 개수
    q1_cnt = 0
    
    r1_sq = r1 * r1
    r2_sq = r2 * r2
    
    # 1-2. 정수인 y값의 개수 세기
    for x in range(1, r2+1):
        x_sq = x * x
        
        # 큰 원(r2) 안쪽 또는 테두리에 들어오는 가장 큰 정수 y는?
        max_y = math.floor(math.sqrt(r2_sq - x_sq))
        
        # 작은 원(r1) 바깥쪽 또는 테두리부터 세기 위해, 작은 원 내부 경계에 있는 정수 y 계산
        if x < r1:
            min_y = math.ceil(math.sqrt(r1_sq - x_sq))
        else:
            min_y = 0
            
        q1_cnt += max_y - min_y + 1
    
    # 2. 최종 답
    answer = q1_cnt * 4
    
    return answer